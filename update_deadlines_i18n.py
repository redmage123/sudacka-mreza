def add_nav_key(lang_dir: Path, lang: str):
    nav_path = lang_dir / "nav.json"
    if not nav_path.exists():
        return
    with open(nav_path, "r", encoding="utf-8") as f:
        data: dict = json.load(f)
    if "deadlines" in data:
        return  # already present
    label = NAV_KEYS.get(lang, "Court Deadline Calculator")
    data["deadlines"] = label
    with open(nav_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"  nav.json [{lang}] updated")


def add_common_keys(lang_dir: Path, lang: str):
    common_path = lang_dir / "common.json"
    if not common_path.exists():
        return
    with open(common_path, "r", encoding="utf-8") as f:
        data: dict = json.load(f)
    changed = False
    for key, translations in TRANSLATIONS.items():
        if key not in data:
            value = translations.get(lang, translations.get("en", key))
            data[key] = value
            changed = True
    if changed:
        with open(common_path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print(f"  common.json [{lang}] updated (+{sum(1 for k in TRANSLATIONS if k not in {})}) keys)")


def main():
    if not LOCALES_DIR.exists():
        print(f"ERROR: {LOCALES_DIR} not found")
        return
    for lang_dir in sorted(LOCALES_DIR.iterdir()):
        if not lang_dir.is_dir():
            continue
        lang = lang_dir.name
        print(f"Processing {lang}...")
        add_nav_key(lang_dir, lang)
        add_common_keys(lang_dir, lang)
    print("\nDone.")


if __name__ == "__main__":
    main()
